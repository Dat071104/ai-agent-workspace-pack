#!/usr/bin/env python3
"""Materialize or update a namespaced copy of this workspace pack in a project.

This is intentionally a copy operation, not a Git clone or submodule. What is
copied is decided in one place (`pack_manifest.shipping_set`): an allowlist of
pack entries, narrowed to Git-tracked files when the source is a repository.
The source pack's own ``_agent_ops/`` is project-specific working memory and
must never become the target project's starting memory.

Every installed copy carries a ``PACK_VERSION`` stamp and a ``PACK_MANIFEST.json``
ownership record. Without the stamp a project has no way to say which pack it is
running; without the manifest a later ``--update`` cannot tell a file the pack
shipped from a file somebody else put in the folder.
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from datetime import date
from pathlib import Path


sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))

from pack_manifest import STAMP_FILE as PACK_VERSION_FILE  # noqa: E402
from pack_manifest import git_tracked, is_git_root, repo_files, shipping_set  # noqa: E402
from pack_manifest import unshipped_untracked, write_manifest  # noqa: E402
from pack_sync import SyncReport, classify_overlap, install_pack, missing_required  # noqa: E402
from pack_sync import UnsafePathError, strip_in_place, update_pack  # noqa: E402
from source_state import looks_like_pack, pack_folder  # noqa: E402
from source_state import worktree_is_clean  # noqa: E402
from ops_gate import REFUSED_EXIT, command_for, preflight_refusal  # noqa: E402


DEFAULT_FOLDER = "ai-agent-workspace-pack"
STAMP_HEADER = (
    "# Generated by scripts/embed_pack.py. Identifies the pack revision this\n"
    "# project is running. Do not hand-edit: refresh it with --update.\n"
)
OVERLAP_REFUSALS = {
    "destination-inside-source": (
        "The destination {destination} lies inside the source pack {source}; copying would "
        "recurse into itself. Choose a --target outside the pack."
    ),
    "source-inside-destination": (
        "The source pack {source} lies inside the destination {destination}; installing would "
        "overwrite the pack that is running. Run embed_pack.py from a pack outside --target/--folder."
    ),
}


def git_output(root: Path, args: list[str]) -> str:
    result = subprocess.run(
        ["git", *args],
        cwd=str(root),
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
        check=False,
    )
    return result.stdout.strip() if result.returncode == 0 else ""


def source_version(source: Path) -> str:
    """Revision of the pack being installed, honest about an unclean source.

    Only a source that is its own repository has a revision of its own: a pack
    copied inside a host project would otherwise be stamped with the HOST's HEAD.
    """

    if not is_git_root(source):
        return "unknown"
    revision = git_output(source, ["rev-parse", "--short", "HEAD"])
    if not revision:
        return "unknown"
    return f"{revision}-dirty" if git_output(source, ["status", "--porcelain"]) else revision


def read_stamp(destination: Path) -> str:
    """The installed pack revision, or an empty string when unstamped."""

    stamp = destination / PACK_VERSION_FILE
    if not stamp.is_file():
        return ""
    for line in stamp.read_text(encoding="utf-8", errors="ignore").splitlines():
        if line.startswith("version:"):
            return line.split(":", 1)[1].strip()
    return ""


def write_stamp(destination: Path, version: str, previous: str = "") -> None:
    lines = [STAMP_HEADER, f"version: {version}", f"installed: {date.today().isoformat()}"]
    if previous:
        lines.append(f"previous: {previous}")
    (destination / PACK_VERSION_FILE).write_text("\n".join(lines) + "\n", encoding="utf-8")


def initialize(destination: Path, target: Path, folder: Path, bridge: bool,
               history: Path | None = None, memory_flag: str = "") -> int:
    command = [
        sys.executable,
        "-B",
        str(destination / "scripts" / "init_project_ops.py"),
        "--target",
        str(target),
        "--embedded-folder",
        folder.as_posix(),
    ]
    if bridge:
        command.append("--install-agents-bridge")
    if history is not None:
        # The embedded copy has no Git history, so only the source pack can prove
        # that an unrecorded legacy policy file is an unedited earlier rendering.
        command += ["--policy-history", str(history)]
    if memory_flag:
        command.append(memory_flag)
    return subprocess.run(command, cwd=str(target), text=True, check=False).returncode


def warn_untracked(source: Path) -> None:
    """New pack files nobody `git add`ed are skipped by the tracked-only rule."""

    skipped = unshipped_untracked(source)
    if skipped:
        print(
            f"WARN {len(skipped)} untracked pack file(s) will NOT be shipped "
            "(git add them to ship; staging is enough, no commit needed):"
        )
        for rel in skipped[:10]:
            print(f"    {rel}")


def preflight(source: Path) -> int:
    """Check the shipping set is runnable BEFORE any write; 0 when it is.

    A set missing a module `init_project_ops.py` imports used to be copied in
    full and then crash the initializer, leaving a half install. The refusal
    names every missing file and why, and the untracked warning is printed here
    so it is shown whatever happens afterwards.
    """

    missing = missing_required(source)
    if missing:
        print(
            f"BLOCKED: {len(missing)} file(s) the pack needs to run would not be shipped; "
            "nothing was written or changed.",
            file=sys.stderr,
        )
        if git_tracked(source) == set():
            print("The source is a Git repository with nothing staged (git add the pack files).", file=sys.stderr)
        for rel, why in list(missing.items())[:10]:
            print(f"    {rel}: {why}", file=sys.stderr)
        if len(missing) > 10:
            print(f"    ... {len(missing) - 10} more", file=sys.stderr)
        print("Fix the above in the source pack, then re-run.", file=sys.stderr)
        return 1
    warn_untracked(source)
    return 0


def memory_flag(args: argparse.Namespace) -> str:
    return "--reset-memory" if args.reset_memory else "--claim-memory" if args.claim_memory else ""


def ownership_preflight(source: Path, target: Path, folder: Path, args: argparse.Namespace) -> int:
    """Stop before writing when init would refuse the project memory already there.

    Without this an update refreshed the pack and only then hit init's
    refusal, leaving a half-finished run. With a memory flag, init decides.
    """

    ops = target / folder / "_agent_ops"
    if memory_flag(args) or not ops.is_dir():
        return 0
    passthrough = [f"--folder {folder.as_posix()}"] if folder.as_posix() != DEFAULT_FOLDER else []
    passthrough += [flag for flag, on in (("--update", args.update), ("--allow-dirty", args.allow_dirty)) if on]
    gate = preflight_refusal(
        target, ops, templates=source / "core-context", ops_relative=f"{folder.as_posix()}/_agent_ops",
        command=command_for(target, Path(__file__), passthrough),
    )
    if gate is None:
        return 0
    print("\n".join(gate.errors), file=sys.stderr)
    print("Nothing in the pack folder was changed.", file=sys.stderr)
    return REFUSED_EXIT


def print_update_report(report: SyncReport) -> None:
    print(f"  files written: {report.written} ({report.unchanged} already current)")
    print(f"  ownership proof: {report.baseline}")
    if report.backed_up:
        print(f"  host-modified or unprovable files overwritten: {len(report.backed_up)}")
        print(f"    originals saved under {report.backup_dir}")
        for rel in report.backed_up[:10]:
            print(f"    {rel}")
        if len(report.backed_up) > 10:
            print(f"    ... {len(report.backed_up) - 10} more")
    if report.removed:
        print(f"  stale pack files removed (proven unmodified): {len(report.removed)}")
        for rel in report.removed[:10]:
            print(f"    {rel}")
        if len(report.removed) > 10:
            print(f"    ... {len(report.removed) - 10} more")
    if report.conflicts:
        print(f"  KEPT, no longer shipped but modified (now yours; delete if unwanted): {len(report.conflicts)}")
        for rel in report.conflicts[:10]:
            print(f"    {rel}")
    if report.unproven:
        print(
            f"  KEPT, cannot prove pack-owned ({len(report.unproven)} file(s) outside the shipping set; "
            "no manifest or usable PACK_VERSION revision):"
        )
        for rel in report.unproven[:10]:
            print(f"    {rel}")


def install_in_place(source: Path, target: Path, folder: Path, version: str,
                     args: argparse.Namespace) -> int:
    """The pack already sits at <target>/<folder>: copy nothing, finish the install."""

    destination = source
    if preflight(source):
        return 1
    refused = ownership_preflight(source, target, folder, args)
    if refused:
        return refused
    if strip_in_place(destination):
        print(f"UPDATED: {destination / 'AGENTS.md'} (generated self-bridge block removed)")
    shipped = shipping_set(destination)
    left = sorted({rel.split("/")[0] for rel in repo_files(destination) - shipped})
    write_stamp(destination, version)
    write_manifest(destination, version, shipped)
    code = initialize(destination, target, folder, bridge=True, memory_flag=memory_flag(args))
    if code != 0:
        print("BLOCKED: in-place initialization failed; no pack file was changed or removed.", file=sys.stderr)
        return code or 1
    print(f"EMBEDDED PACK (in place): {destination} (version {version})")
    if left:
        print("  not part of the shipping set, left untouched (remove by hand if unwanted): " + ", ".join(left))
    return 0


def install_fresh(source: Path, destination: Path, target: Path, folder: Path, version: str,
                  args: argparse.Namespace) -> int:
    if preflight(source):
        return 1
    try:
        count = install_pack(source, destination, version)
    except OSError as error:
        # The destination did not exist before this run, so removing it is safe.
        shutil.rmtree(destination, ignore_errors=True)
        print(f"BLOCKED: copy failed ({error}); nothing was left behind.", file=sys.stderr)
        return 1
    write_stamp(destination, version)
    code = initialize(destination, target, folder, bridge=True, memory_flag=memory_flag(args))
    if code != 0:
        print(
            f"BLOCKED: copied pack remains at {destination}; initialization failed without removing it.",
            file=sys.stderr,
        )
        return code or 1
    print(f"EMBEDDED PACK: {destination} (version {version}, {count} files)")
    print(
        "Shipped the allowlisted pack files (Git-tracked only when the source is a repository); "
        "local/ignored files, tests/, examples/ and the source _agent_ops were not copied; "
        "a fresh nested ops folder was initialized."
    )
    return 0


def run_update(parser: argparse.ArgumentParser, args: argparse.Namespace, source: Path,
               destination: Path, target: Path, folder: Path, version: str) -> int:
    if not destination.is_dir() or not looks_like_pack(destination):
        parser.error(f"No installed pack to update at {destination}; run without --update to install one.")
    clean = worktree_is_clean(target)
    if clean is None and not args.allow_dirty:
        parser.error(
            "Target is not a Git repository, so an update would not be revertible. "
            "Commit it to Git first, or pass --allow-dirty to accept that risk."
        )
    if clean is False and not args.allow_dirty:
        parser.error(
            "Target worktree has uncommitted changes. Commit or stash them first so the update "
            "is revertible, or pass --allow-dirty."
        )

    if preflight(source):
        return 1
    refused = ownership_preflight(source, target, folder, args)
    if refused:
        return refused
    previous = read_stamp(destination)
    if previous == version:
        print(f"UP TO DATE: {destination} already runs pack version {version}.")
        print("Refreshing content anyway is safe: re-run after committing if you edited the pack in place.")
    try:
        report = update_pack(source, destination, version, previous)
    except UnsafePathError as error:
        print(f"BLOCKED: {error}; the pack folder was not changed.", file=sys.stderr)
        return 1
    write_stamp(destination, version, previous)
    print(f"UPDATED PACK: {destination}")
    print(f"  version: {previous or 'unstamped'} -> {version}")
    print_update_report(report)
    print("  project memory: _agent_ops/ records untouched; init below refreshes only provably unedited generated policy")

    code = initialize(destination, target, folder, bridge=False,
                      history=source if is_git_root(source) else None, memory_flag=memory_flag(args))
    if code != 0:
        print(
            f"BLOCKED: pack content was refreshed but init stopped (exit {code}); see its message above. "
            "Re-run --update once that is resolved.",
            file=sys.stderr,
        )
        return code or 1
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Copy this pack into a project, or update a copy already installed there."
    )
    parser.add_argument("--target", required=True, help="Target project directory.")
    parser.add_argument(
        "--folder",
        default=DEFAULT_FOLDER,
        help="Pack folder name, directly under the target project root.",
    )
    parser.add_argument(
        "--update",
        action="store_true",
        help=(
            "Refresh a pack already installed at --folder. Overwrites pack content (saving any "
            "host-modified copy first) and removes files this revision no longer ships only when "
            "they are provably unmodified pack files; never touches _agent_ops/."
        ),
    )
    parser.add_argument(
        "--allow-dirty",
        action="store_true",
        help="Update even though the target worktree has uncommitted changes.",
    )
    memory = parser.add_mutually_exclusive_group()
    memory.add_argument(
        "--claim-memory",
        action="store_true",
        help="Passed to init: adopt existing memory not yet proven this project's (e.g. an install from before stamps).",
    )
    memory.add_argument(
        "--reset-memory",
        action="store_true",
        help="Passed to init: back up that memory completely, then start from fresh templates.",
    )
    args = parser.parse_args()

    target = Path(args.target).expanduser().resolve()
    if not target.exists() or not target.is_dir():
        parser.error(f"Target must be an existing directory: {target}")
    try:
        folder = pack_folder(args.folder)
    except ValueError as error:
        parser.error(str(error))

    source = Path(__file__).resolve().parents[1]
    destination = target / folder
    version = source_version(source)

    overlap = classify_overlap(source, destination)
    if overlap in OVERLAP_REFUSALS:
        parser.error(OVERLAP_REFUSALS[overlap].format(source=source, destination=destination.resolve()))
    if args.update:
        if overlap == "same":
            parser.error("Refusing to update this pack's own source checkout.")
        return run_update(parser, args, source, destination, target, folder, version)

    if overlap == "same":
        return install_in_place(source, target, folder, version, args)
    if destination.exists():
        parser.error(
            f"Destination already exists: {destination}\n"
            "       Re-run with --update to refresh the installed pack in place."
        )
    if source.parent == target:
        print(
            f"NOTE: this pack already sits in the target as '{source.name}'. To install it in "
            f"place instead of copying, pass --folder {source.name}."
        )
    return install_fresh(source, destination, target, folder, version, args)


if __name__ == "__main__":
    raise SystemExit(main())
